"""Developer tool: render the real compiled agent graph for review.

Ad-hoc, not a pytest file, meant to be run by hand from the project root.

Why this beats a hand-drawn diagram: it renders what `build_agent()` actually
compiled, so it can't drift from the code the way notes/sequence-diagrams.md
can. If an edge is missing here, it's missing in the app.

Uses a stub model, so it needs no API key and makes no network call.

    .venv\\Scripts\\python.exe devtools\\try_graph_viz.py              # print mermaid
    .venv\\Scripts\\python.exe devtools\\try_graph_viz.py --write      # refresh notes/graph-visual.md
    .venv\\Scripts\\python.exe devtools\\try_graph_viz.py --ascii      # ASCII (needs grandalf)
    .venv\\Scripts\\python.exe devtools\\try_graph_viz.py --png out.png  # PNG via mermaid.ink (network)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any, Optional

# The project root, one level up: this file lives in devtools/, and the
# agent it renders is imported from the root.
PROJECT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT))

from langchain_core.language_models import BaseChatModel
from langchain_core.messages import AIMessage
from langchain_core.outputs import ChatGeneration, ChatResult

from agent.graph import build_agent

NOTES_PATH = PROJECT / "notes" / "graph-visual.md"


class StubChatModel(BaseChatModel):
    """Stands in for ChatOpenAI so rendering needs no key and calls nothing."""

    def bind_tools(self, tools: Any, *, tool_choice: Optional[str] = None, **kwargs: Any):
        return self

    def _generate(self, messages, stop=None, run_manager=None, **kwargs) -> ChatResult:
        return ChatResult(generations=[ChatGeneration(message=AIMessage(content="stub"))])

    @property
    def _llm_type(self) -> str:
        return "stub"


HEADER = """# Agent graph - auto-generated

**Generated by `try_graph_viz.py --write`. Do not hand-edit.** This renders what
`agent/graph.py:build_agent()` actually compiled, so unlike `sequence-diagrams.md`
it cannot drift from the code. Open Preview in VS Code (Ctrl+Shift+V) to see it.

## How to read it

- **Dotted arrows are conditional edges** - a routing function decides. There are
  four of them: `__start__` picks the station, each station decides whether it needs
  tools, the tools node hands control back, and `count_rejection` picks which of the
  two rejection answers to give.
- **Solid arrows are unconditional** - `web_search_ideas`, `ask_goal_again` and
  `checkin_done` all go straight to `__end__`. They are the turn's last word.
- **`ask`, `suggest`, `follow_up` and `debate` are the only nodes that call a model.**
  `count_rejection`, `ask_goal_again` and `checkin_done` are code: noticing a "no",
  asking a fixed question and ending a check-in are not judgement calls.

## Reviewing it

Two things worth checking against your intent:

1. Every station reaches `tools` and `__end__`, and only `follow_up` reaches the log -
   not because the prompt says so, but because `log_checkin` is bound nowhere else.
   The bound-tool matrix is not visible in this picture; tests/test_stations.py has it.
2. `tools` routes back to a *station*, never to `__end__`. A tool result the model
   never gets to read would be a silent dead end, and this is where it would show.

```mermaid
"""

FOOTER = "```\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Render the compiled agent graph")
    parser.add_argument("--write", action="store_true", help=f"Write {NOTES_PATH.name}")
    parser.add_argument("--ascii", action="store_true", help="ASCII art (needs grandalf)")
    parser.add_argument("--png", metavar="PATH", help="PNG via mermaid.ink (needs network)")
    args = parser.parse_args()

    graph = build_agent(model=StubChatModel()).get_graph()

    if args.ascii:
        try:
            graph.print_ascii()
        except ImportError:
            print("ASCII rendering needs grandalf:")
            print("  .venv\\Scripts\\python.exe -m pip install grandalf")
        return

    if args.png:
        Path(args.png).write_bytes(graph.draw_mermaid_png())
        print(f"Wrote {args.png}")
        return

    mermaid = graph.draw_mermaid()
    if args.write:
        NOTES_PATH.parent.mkdir(parents=True, exist_ok=True)
        NOTES_PATH.write_text(HEADER + mermaid + FOOTER, encoding="utf-8")
        print(f"Wrote {NOTES_PATH}")
    else:
        print(mermaid)


if __name__ == "__main__":
    main()
