"""Scratch script: render the real compiled agent graph for review.

Same `try_*.py` convention as try_safety.py / try_agent.py -- ad-hoc, not a
pytest file, meant to be run by hand.

Why this beats a hand-drawn diagram: it renders what `build_agent()` actually
compiled, so it can't drift from the code the way notes/sequence-diagrams.md
can. If an edge is missing here, it's missing in the app.

Uses a stub model, so it needs no API key and makes no network call.

    .venv\\Scripts\\python.exe try_graph_viz.py              # print mermaid
    .venv\\Scripts\\python.exe try_graph_viz.py --write      # refresh notes/graph-visual.md
    .venv\\Scripts\\python.exe try_graph_viz.py --ascii      # ASCII (needs grandalf)
    .venv\\Scripts\\python.exe try_graph_viz.py --png out.png  # PNG via mermaid.ink (network)
"""
from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any, Optional

from langchain_core.language_models import BaseChatModel
from langchain_core.messages import AIMessage
from langchain_core.outputs import ChatGeneration, ChatResult

from agent.graph import build_agent

NOTES_PATH = Path(__file__).resolve().parent / "notes" / "graph-visual.md"


class StubChatModel(BaseChatModel):
    """Stands in for ChatOpenAI so rendering needs no key and calls nothing."""

    def bind_tools(self, tools: Any, *, tool_choice: Optional[str] = None, **kwargs: Any):
        return self

    def _generate(self, messages, stop=None, run_manager=None, **kwargs) -> ChatResult:
        return ChatResult(generations=[ChatGeneration(message=AIMessage(content="stub"))])

    @property
    def _llm_type(self) -> str:
        return "stub"


HEADER = """# Agent graph — auto-generated

**Generated by `try_graph_viz.py --write`. Do not hand-edit.** This renders what
`agent/graph.py:build_agent()` actually compiled, so unlike `sequence-diagrams.md`
it cannot drift from the code. Open Preview in VS Code (Ctrl+Shift+V) to see it.

## How to read it

- **Solid arrows are unconditional edges** — they always fire. `classify → log_write →
  history_lookup` is the deterministic spine: once the model requests `log_mood`, the
  entry gets classified, written, and checked against history whether or not the model
  "wants" that. This is the stage-15 guarantee, and it is visible here as solid lines.
- **Dotted arrows are conditional edges** — a routing function decides. All of them
  leave `agent` or `history_lookup`, i.e. every real choice in the graph is made in
  exactly two places.
- `classify_entry` is not a node the model can reach; it runs *inside* the `classify`
  node and is deliberately absent from the bound tool list.

## Reviewing it

Two things worth checking against your intent:

1. `agent` has three exits (`__end__`, `classify`, `tools`) — reply, log, or run some
   other tool. There is no fourth path, so anything the agent does must be one of those.
2. `history_lookup` routes back to `tools` as well as `agent`. That's the mixed-tool-call
   case: a model that asks for `log_mood` *and* something else in one message gets the
   log pipeline first, then the remaining calls, with no double-execution.

```mermaid
"""

FOOTER = "```\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Render the compiled agent graph")
    parser.add_argument("--write", action="store_true", help=f"Write {NOTES_PATH.name}")
    parser.add_argument("--ascii", action="store_true", help="ASCII art (needs grandalf)")
    parser.add_argument("--png", metavar="PATH", help="PNG via mermaid.ink (needs network)")
    args = parser.parse_args()

    graph = build_agent(model=StubChatModel()).get_graph()

    if args.ascii:
        try:
            graph.print_ascii()
        except ImportError:
            print("ASCII rendering needs grandalf:")
            print("  .venv\\Scripts\\python.exe -m pip install grandalf")
        return

    if args.png:
        Path(args.png).write_bytes(graph.draw_mermaid_png())
        print(f"Wrote {args.png}")
        return

    mermaid = graph.draw_mermaid()
    if args.write:
        NOTES_PATH.parent.mkdir(parents=True, exist_ok=True)
        NOTES_PATH.write_text(HEADER + mermaid + FOOTER, encoding="utf-8")
        print(f"Wrote {NOTES_PATH}")
    else:
        print(mermaid)


if __name__ == "__main__":
    main()
